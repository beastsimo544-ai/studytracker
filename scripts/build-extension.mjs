import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

function parseEnvFile(filePath) {
  const env = {};
  if (!fs.existsSync(filePath)) return env;
  const content = fs.readFileSync(filePath, "utf8");
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eqIdx = line.indexOf("=");
    if (eqIdx === -1) continue;
    const key = line.slice(0, eqIdx).trim();
    let value = line.slice(eqIdx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

const fileEnv = parseEnvFile(path.resolve(".env.local"));
const supabaseUrl =
  process.env.NEXT_PUBLIC_SUPABASE_URL ||
  fileEnv.NEXT_PUBLIC_SUPABASE_URL ||
  "";
const supabaseAnonKey =
  process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ||
  fileEnv.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY ||
  "";
const siteUrl =
  process.env.NEXT_PUBLIC_SITE_URL ||
  fileEnv.NEXT_PUBLIC_SITE_URL ||
  "https://studytracker-e2vs.vercel.app";

if (!supabaseUrl || !supabaseAnonKey) {
  console.error(
    "Missing NEXT_PUBLIC_SUPABASE_URL or NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY in .env.local / environment."
  );
  process.exit(1);
}

const extensionDir = path.resolve("extension");
const configJs = `// Auto-generated by scripts/build-extension.mjs
self.STUDYTRACKER_CONFIG = {
  SUPABASE_URL: ${JSON.stringify(supabaseUrl)},
  SUPABASE_ANON_KEY: ${JSON.stringify(supabaseAnonKey)},
  DASHBOARD_URL: ${JSON.stringify(siteUrl.replace(/\/+$/, "") + "/dashboard")},
};
`;
fs.writeFileSync(path.join(extensionDir, "config.js"), configJs, "utf8");

const iconSrc = path.resolve("public/playstore-icon-512.png");
const iconDest = path.join(extensionDir, "icon.png");
if (fs.existsSync(iconSrc)) {
  fs.copyFileSync(iconSrc, iconDest);
}

const zipDest = path.resolve("public/StudyTracker-Extension.zip");
if (fs.existsSync(zipDest)) {
  fs.unlinkSync(zipDest);
}

const archiveCmd = `Compress-Archive -Path '${extensionDir}\\*' -DestinationPath '${zipDest}' -Force`;
const zipRes = spawnSync(
  "powershell.exe",
  ["-NoProfile", "-Command", archiveCmd],
  { stdio: "inherit" }
);

if (zipRes.status !== 0) {
  process.exit(zipRes.status ?? 1);
}

console.log(`Built ${zipDest}`);
